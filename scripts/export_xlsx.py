def border(t=thin, b=thin, l=thin, r=thin):
    return Border(top=t, bottom=b, left=l, right=r)

FULL_THIN   = border()
FULL_MEDIUM = border(thick, thick, thick, thick)

def style(c, bold=False, size=FONT_SIZE, fg="000000", bg=None,
          h="left", v="center", wrap=True, bdr=FULL_THIN, italic=False):
    c.font = Font(name=FONT_NAME, size=size, bold=bold, color=fg, italic=italic)
    if bg:
        c.fill = PatternFill("solid", fgColor=bg)
    c.alignment = Alignment(horizontal=h, vertical=v, wrap_text=wrap)
    c.border = bdr

def write(ws, row, col, val, **kw):
    c = ws.cell(row=row, column=col)
    c.value = val
    style(c, **kw)
    return c

def mwrite(ws, row, c1, c2, val, **kw):
    ws.merge_cells(start_row=row, start_column=c1, end_row=row, end_column=c2)
    c = ws.cell(row=row, column=c1)
    c.value = val
    style(c, **kw)

